export type AssessmentQuestionChange = Pick<
  AssessmentQuestion,
  | "id"
  | "text"
  | "translations"
  | "domain"
  | "additionalDomains"
  | "skillAgeMonths"
>;

type StoredAssessmentQuestionChanges = Partial<
  Record<AssessmentInstrument, AssessmentQuestionChange[]>
>;

const QUESTION_CHANGES_STORAGE_KEY =
  "nasp.ei.questionnaire-question-changes.v1";
const assessmentInstruments: AssessmentInstrument[] = ["KID", "RCDI-2000"];

function hydrateBundledQuestionTranslations() {
  assessmentInstruments.forEach((instrument) => {
    assessmentQuestionBank[instrument].forEach((question) => {
      question.translations = getSeededQuestionTranslations(
        question.id,
        question.text,
      );
    });
  });
}

function readStoredQuestionChanges(): StoredAssessmentQuestionChanges {
  if (typeof window === "undefined") {
    return {};
  }

  try {
    const stored = window.localStorage.getItem(QUESTION_CHANGES_STORAGE_KEY);
    return stored
      ? (JSON.parse(stored) as StoredAssessmentQuestionChanges)
      : {};
  } catch {
    return {};
  }
}

function applyQuestionChanges(
  instrument: AssessmentInstrument,
  changes: AssessmentQuestionChange[],
) {
  const changesById = new Map(changes.map((change) => [change.id, change]));

  assessmentQuestionBank[instrument].forEach((question) => {
    const change = changesById.get(question.id);

    if (!change) {
      return;
    }

    question.text = change.text;

    if (change.translations) {
      const nonEmptyTranslations = Object.fromEntries(
        Object.entries(change.translations).filter(([, value]) =>
          value?.trim(),
        ),
      ) as QuestionnaireTranslations;

      question.translations = {
        ...question.translations,
        ...nonEmptyTranslations,
      };
    }

    question.domain = change.domain;
    question.additionalDomains = change.additionalDomains
      ? [...change.additionalDomains]
      : undefined;
    question.skillAgeMonths = change.skillAgeMonths;
  });
}

function hydrateStoredQuestionChanges() {
  const storedChanges = readStoredQuestionChanges();

  assessmentInstruments.forEach((instrument) => {
    const changes = storedChanges[instrument];

    if (changes?.length) {
      applyQuestionChanges(instrument, changes);
    }
  });
}

export function saveAssessmentQuestionChanges(
  instrument: AssessmentInstrument,
  changes: AssessmentQuestionChange[],
) {
  applyQuestionChanges(instrument, changes);

  if (typeof window !== "undefined") {
    const storedChanges = readStoredQuestionChanges();
    storedChanges[instrument] = changes;
    window.localStorage.setItem(
      QUESTION_CHANGES_STORAGE_KEY,
      JSON.stringify(storedChanges),
    );
  }
}

