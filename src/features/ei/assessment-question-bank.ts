export type AssessmentInstrument = "KID" | "RCDI-2000";

export type DevelopmentDomain =
  | "cognitive"
  | "motor"
  | "language"
  | "selfCare"
  | "social"
  | "grossMotor"
  | "fineMotor"
  | "expressiveLanguage"
  | "receptiveLanguage";

export type AssessmentQuestion = {
  id: string;
  instrument: AssessmentInstrument;
  domain: DevelopmentDomain;
  additionalDomains?: DevelopmentDomain[];
  text: string;
  translations?: QuestionnaireTranslations;
  skillAgeMonths: number;
  sourceNumber: number;
  sourceLanguage: "ru";
};

export const assessmentDomainOrder: Record<
  AssessmentInstrument,
  DevelopmentDomain[]
> = {
  KID: ["cognitive", "motor", "language", "selfCare", "social"],
  "RCDI-2000": [
    "social",
    "selfCare",
    "grossMotor",
    "fineMotor",
    "expressiveLanguage",
    "receptiveLanguage",
  ],
};

export function sortAssessmentQuestionsForDisplay(
  instrument: AssessmentInstrument,
  questions: readonly AssessmentQuestion[],
) {
  if (instrument === "KID") {
    return [...questions].sort(
      (left, right) => left.sourceNumber - right.sourceNumber,
    );
  }

  const domainPositions = new Map(
    assessmentDomainOrder[instrument].map((domain, index) => [domain, index]),
  );

  return [...questions].sort((left, right) => {
    const domainDifference =
      (domainPositions.get(left.domain) ?? Number.MAX_SAFE_INTEGER) -
      (domainPositions.get(right.domain) ?? Number.MAX_SAFE_INTEGER);

    return domainDifference || left.sourceNumber - right.sourceNumber;
  });
}

